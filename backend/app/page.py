_env = Environment(autoescape=True)
_env.filters["tojson"] = json.dumps


def build_html(post: BlogPost, primary: str, words: int) -> str:
    used: set = set()
    L = post.internal_links
    intro = [linkify(p, L, used) for p in post.intro]
    sections = []
    for s in post.sections:
        sections.append({
            "heading": s.heading, "bullets": s.bullets,
            "paragraphs": [linkify(p, L, used) for p in s.paragraphs],
            "subsections": [{"heading": u.heading, "bullets": u.bullets, "paragraphs": [linkify(p, L, used) for p in u.paragraphs]} for u in s.subsections],
        })
    date = datetime.now(timezone.utc).strftime("%d %b %Y")
    iso = datetime.now(timezone.utc).isoformat()
    ld = [
        {"@context": "https://schema.org", "@type": "Article", "headline": post.seo_title, "description": post.meta_description,
         "datePublished": iso, "mainEntityOfPage": f"{BASE}/blog/{post.slug}", "author": {"@type": "Organization", "name": "Appin Technology Coimbatore"}},
        {"@context": "https://schema.org", "@type": "FAQPage",
         "mainEntity": [{"@type": "Question", "name": f.question, "acceptedAnswer": {"@type": "Answer", "text": f.answer}} for f in post.faqs]},
    ]
    jsonld = Markup(json.dumps(ld).replace("</", "<\\/"))
    return _env.from_string(TEMPLATE).render(post=post, intro=intro, sections=sections, css=Markup(CSS), jsonld=jsonld, base=BASE,
                                             slug=post.slug, site=SITE, primary=primary, date=date,
                                             read_min=max(1, round(words / 220)))


def build_index(pages: list[dict]) -> str:
    return _env.from_string(INDEX).render(pages=pages, css=Markup(CSS))
